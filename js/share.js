// FlipTheSAA — Share a passed timed exam on LinkedIn / WhatsApp
import { PASSING_SCORE } from './config.js';

/*
 * HOW THE LINK PREVIEW WORKS (no backend):
 * LinkedIn and WhatsApp read Open Graph tags without running JavaScript, so the
 * card can't be drawn per person, and a timed score can be any whole number
 * (the scored questions are worth different points). The shared card and text
 * therefore say "passed" and leave the score out: one pre-built static page
 * share/passed.html whose og:image is share/img/passed.png, which redirects a
 * human visitor to the home page. Both are generated by scripts/build-share-cards.mjs.
 * The older share/{score}.html pages (720 ... 1000) stay so links already shared keep working.
 */
const SITE_URL = 'https://www.flipthesaa.com';

/**
 * WHAT IT DOES: True when this result may be shared: a submitted TIMED exam
 * that passed. Review sessions and mistake drills (which are review sessions)
 * never qualify.
 */
export function canShare(session, score) {
  return !!session && session.mode === 'timed' && !session.drill && !!score && score.passed &&
    score.points >= PASSING_SCORE;
}

export function shareUrl() {
  return `${SITE_URL}/share/passed.html`;
}

export function shareText() {
  return `I just passed a full AWS SAA-C03 mock exam.\n\n` +
    `Want to practise SAA mock exams for free? ${shareUrl()}`;
}

function setStatus(message) {
  const el = document.getElementById('shareStatus');
  if (el) el.textContent = message;
}

/**
 * WHAT IT DOES: Copies text to the clipboard; falls back to selecting the
 * textarea so the person can copy it by hand. Resolves true when copied.
 */
async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const box = document.getElementById('shareText');
    box?.focus();
    box?.select();
    return false;
  }
}

/**
 * WHAT IT DOES: Opens the share dialog for a passed timed exam (the card and the text carry no score)
 */
export function openShareDialog() {
  const dialog = document.getElementById('shareDialog');
  if (!dialog) return;
  const img = document.getElementById('shareCardImg');
  img.src = 'share/img/passed.png';
  img.alt = 'Practice exam result card: passed an AWS SAA-C03 mock exam.';
  document.getElementById('shareText').value = shareText();
  setStatus('');
  if (typeof dialog.showModal === 'function') dialog.showModal();
  else dialog.setAttribute('open', '');
}

/**
 * WHAT IT DOES: Wires the dialog's buttons once (called from main.js).
 * The buttons read the textarea, so the person's own edits are what gets shared.
 */
export function initShareDialog() {
  const textOf = () => document.getElementById('shareText')?.value.trim() || '';

  document.getElementById('shareLinkedInBtn')?.addEventListener('click', async () => {
    const text = textOf();
    // LinkedIn's text pre-fill is undocumented: copy first, so an empty post box can be pasted into
    const copied = await copyText(text);
    window.open(`https://www.linkedin.com/feed/?shareActive=true&text=${encodeURIComponent(text)}`, '_blank', 'noopener');
    setStatus(copied ? 'Text copied. If LinkedIn opens with an empty post box, paste it in.' : 'If LinkedIn opens with an empty post box, copy the text above and paste it in.');
  });

  document.getElementById('shareWhatsAppBtn')?.addEventListener('click', () => {
    window.open(`https://wa.me/?text=${encodeURIComponent(textOf())}`, '_blank', 'noopener');
    setStatus('');
  });

  document.getElementById('shareCopyBtn')?.addEventListener('click', async () => {
    setStatus((await copyText(textOf())) ? 'Text copied.' : 'Press Ctrl+C (or Copy on your phone) to copy the selected text.');
  });
}
